// ── Impact tab ────────────────────────────────────────────────────────────────

function ImpactTab({ data, scenario, size }: { data: NarrativePageData; scenario: string; size: string }) {
  const emps = data.top_impact_employees
  const [selectedId, setSelectedId] = useState(emps[0]?.employee_id ?? '')
  const [result, setResult]         = useState<NarrativeResult | null>(null)
  const [loading, setLoading]       = useState(false)

  const generate = useCallback(async () => {
    if (!selectedId) return
    setLoading(true)
    try {
      const r = await api.narrative.impact({ scenario, size, employee_id: selectedId, budget_pct: 0.8 })
      setResult(r)
    } finally { setLoading(false) }
  }, [selectedId, scenario, size])

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
      <div style={{
        backgroundColor: 'var(--surface)', borderRadius: 'var(--radius)',
        border: '1px solid rgba(255,255,255,0.06)', padding: '20px 24px',
      }}>
        <EmployeeSelector employees={emps} selectedId={selectedId}
          onSelect={id => { setSelectedId(id); setResult(null) }}
          label="Select employee — sorted by impact score" />
        <div style={{ marginTop: 16 }}>
          <GenerateButton onClick={generate} loading={loading}
            label="Explain Impact Score" />
        </div>
      </div>

      {result?.source_data.drivers && (
        <DriverBreakdown drivers={result.source_data.drivers as NarrativeDriver[]} />
      )}
      <NarrativePanel result={result} loading={loading} />
    </div>
  )
}

