// ── Palette helpers ───────────────────────────────────────────────────────────

function dirColor(direction: string): string {
  return direction === 'risk' ? '#e07030'
    : direction === 'protective' ? '#1a8c4e'
    : direction === 'positive'   ? '#2a7ab0'
    : 'rgba(255,255,255,0.4)'
}

function pct(n: number): string { return `${(n * 100).toFixed(0)}%` }

